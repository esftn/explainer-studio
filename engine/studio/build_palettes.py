"""Regenerates palettes.json from the colour list below and validates contrast (text >= 4.5:1 on its background, accents >= 2.4:1 (highlighter blocks behind text)).
Edit a colour here, run `python3 build_palettes.py`, never edit palettes.json by hand."""
import colorsys, json, pathlib

def lum(h):
    h = h.lstrip('#'); r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
def cr(a, b):
    la, lb = lum(a), lum(b); return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)
def sat(h):
    h = h.lstrip('#'); r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]; return colorsys.rgb_to_hsv(r, g, b)[1]

