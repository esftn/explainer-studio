bad = 0
for pid, label, fam, motif, paper, ink, cs in P:
    cols = {'paper': paper, 'ink': ink, 'c1': cs[0], 'c2': cs[1], 'c3': cs[2], 'c4': cs[3]}
    themes = []
    for name in ('paper', 'c1', 'c2', 'c3', 'c4', 'ink'):
        bg = cols[name]
        text = next((t for t in (ink, paper, '#FFFFFF', '#000000') if cr(t, bg) >= 4.5), None)
        if not text: continue
        accs = [cols[k] for _, k in sorted(((cr(v, bg), k) for k, v in cols.items() if k != name and v != text and cr(v, bg) >= 2.4), reverse=True)]
