#!/usr/bin/env python3
"""Move an episode between the cloud workspace and the creator's Mac in ONE verified step (stdlib + ffmpeg).
The same file runs on both sides; new_project.py / skeleton copy it to videoNN/.studio/pack.py on the Mac.

  pack.py skeleton <videoNN>                       create the standard folders (run on the Mac at setup)
  pack.py pack <project> --set S --out <dir> [--name N] [--mb 14] [--no-images]
        S = project : working files, docs, VO, images (no renders)           start/end of a stage
            preview : drafts/*_preview.mp4 + out/keys_*.jpg                    preview gate
            final   : project + finals in out/                                 delivery
  pack.py unpack <dir> --name N --into <project> [--verify-only]   join parts, check, extract, verify every file
  pack.py check <project> [--final] [--working]    standard layout check (out/ = finals only on the Mac;
                                                   --working = the cloud copy, where out/ also holds working files)

Parts are ≤ --mb MB (bridge transfer cap) and go to videoNN/_to_delete/ on the Mac (the connected folder can't
delete; the creator empties it). Verification: sha256 per file; media whose bytes changed in transit (the Mac adds
a C2PA box to some MP4/PNG files) are compared by decoded content (ffmpeg -f md5) instead.
Exit code 0 = verified, 1 = something is missing or different (details printed)."""
import argparse, fnmatch, hashlib, io, json, os, pathlib, shutil, subprocess, sys, tarfile, time
sys.dont_write_bytecode = True      # the Mac folder can't delete: no __pycache__ litter

LAYOUT = ['out', 'docs', 'drafts', 'vo/raw', 'vo/unused', 'img', 'images', '_to_delete', '.studio']
FINALS = ['*_reel_9x16.mp4', '*_feed_4x5.mp4', 'cover_reel_9x16.png', 'cover_feed_4x5.png', 'captions.bn_IN.srt', 'captions.en_US.srt', 'publish.txt']
NEVER = ['node_modules', '_to_delete', '.cache', '__pycache__', '.DS_Store', '*.part_*', '*.manifest.json', '.lock.json', '.studio_base.json']
WORK_SKIP_OUT = True          # out/ only travels as finals
MEDIA = ('.mp4', '.mov', '.png', '.jpg', '.jpeg', '.wav', '.mp3', '.m4a')


def sha(f):
    h = hashlib.sha256()
    with open(f, 'rb') as fh:
        for b in iter(lambda: fh.read(1 << 20), b''): h.update(b)
    return h.hexdigest()


def decode_md5(f):
    if not shutil.which('ffmpeg'): return None
    r = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(f), '-map', '0:v:0?', '-map', '0:a:0?', '-f', 'md5', '-'],
                       capture_output=True, text=True)
    return r.stdout.strip() or None


def skip(rel):
    parts = rel.split('/')
    return any(fnmatch.fnmatch(p, pat) for p in parts for pat in NEVER)


def files_for(P, kind, no_images):
    out = []
    for f in sorted(P.rglob('*')):
        if not f.is_file(): continue
        rel = f.relative_to(P).as_posix()
        if skip(rel): continue
        top = rel.split('/')[0]
        if kind == 'preview':
            if (top == 'drafts' and fnmatch.fnmatch(f.name, '*_preview.mp4')) or (top == 'out' and fnmatch.fnmatch(f.name, 'keys_*.jpg')):
                out.append(rel)
            continue
        if no_images and top == 'images': continue
        if top == 'out':
            if kind == 'final' and '/' not in rel[4:] and any(fnmatch.fnmatch(f.name, p) for p in FINALS): out.append(rel)
            continue
        if top == 'drafts' and f.suffix.lower() in ('.mp4', '.mov'): continue     # previews/no-cover copies travel only with --set preview
        if rel.startswith('vo/') and f.suffix.lower() == '.wav' and f.parent.name == 'vo': continue   # regenerated by vo_prep
        out.append(rel)
    return out


def cmd_pack(a):
    P = pathlib.Path(a.project).resolve(); O = pathlib.Path(a.out).resolve(); O.mkdir(parents=True, exist_ok=True)
    name = a.name or f'{P.name}_{a.set}_{time.strftime("%m%d-%H%M")}'
    if a.guard:                                   # v0.6 push guard: the Mac copy must still be what was pulled
        import guard
        problems = guard.check_push_data(P, json.loads(pathlib.Path(a.guard).read_text()), a.who)
        if problems and not a.force:
            print(f"REFUSED: pushing would overwrite someone else's work in {P.name}:")
            for p in problems[:25]: print('  · ' + p)
            print('Do NOT push. Pull the Mac copy again, merge what you need, or ask the creator which version wins.'); sys.exit(2)
        print('guard: OK — the Mac copy is unchanged since the pull' + (' (FORCED)' if problems else ''))
    rels = files_for(P, a.set, a.no_images)
    if not rels: sys.exit(f'nothing to pack for --set {a.set}')
    man = {'name': name, 'set': a.set, 'from': str(P), 'time': time.strftime('%Y-%m-%d %H:%M'), 'no_images': bool(a.no_images), 'files': {}}
    import tempfile
    tf = pathlib.Path(tempfile.mkdtemp(prefix='pack_')) / f'{name}.tar'      # the Mac folder can't delete: the temp archive lives outside it
    with tarfile.open(tf, 'w') as t:
        for rel in rels:
            f = P / rel; e = {'sha': sha(f), 'size': f.stat().st_size}
            if f.suffix.lower() in MEDIA and f.suffix.lower() in ('.mp4', '.mov', '.png'):
                e['dec'] = decode_md5(f)
            man['files'][rel] = e; t.add(f, arcname=rel)
    man['tar_sha'] = sha(tf); data = tf.read_bytes(); n = int(a.mb * 1024 * 1024); parts = []
    for i in range(0, len(data), n):
        p = O / f'{name}.part_{i // n:02d}'; p.write_bytes(data[i:i + n]); parts.append(p.name)
    shutil.rmtree(tf.parent, ignore_errors=True); man['parts'] = parts
    (O / f'{name}.manifest.json').write_text(json.dumps(man, ensure_ascii=False, indent=1))
    tot = sum(e['size'] for e in man['files'].values()) / 1e6
    print(f'packed {len(rels)} files ({tot:.1f} MB) → {len(parts)} part(s) + {name}.manifest.json in {O}')
    print('NAME', name)


def cmd_unpack(a):
    D = pathlib.Path(a.dir).resolve(); P = pathlib.Path(a.into).resolve(); P.mkdir(parents=True, exist_ok=True)
    mf = D / f'{a.name}.manifest.json'
    if not mf.exists(): sys.exit(f'FAIL: manifest {mf.name} missing in {D}')
    man = json.loads(mf.read_text()); bad = []
    missing = [p for p in man['parts'] if not (D / p).exists()]
    if missing: sys.exit(f'FAIL: missing part(s) {missing}')
    buf = io.BytesIO()
    for p in man['parts']: buf.write((D / p).read_bytes())
    if hashlib.sha256(buf.getvalue()).hexdigest() != man['tar_sha']: sys.exit('FAIL: joined archive is corrupt (sha mismatch) — transfer the parts again')
    buf.seek(0)
    if not a.verify_only:
      with tarfile.open(fileobj=buf) as t:
        for m in t.getmembers():
              if m.name.startswith('/') or '..' in pathlib.PurePosixPath(m.name).parts: sys.exit(f'FAIL: unsafe path {m.name}')
              if not m.isfile(): continue
              dst = P / m.name; dst.parent.mkdir(parents=True, exist_ok=True)
              with t.extractfile(m) as src, open(dst, 'wb') as o: shutil.copyfileobj(src, o)
    by_dec = 0
    for rel, e in man['files'].items():
        f = P / rel
        if not f.exists(): bad.append(f'missing {rel}'); continue
        if sha(f) == e['sha']: continue
        if e.get('dec') and decode_md5(f) == e['dec']: by_dec += 1; continue
        bad.append(f'different {rel}')
    for b in bad: print('FAIL', b)
    if not bad and not a.verify_only and man.get('set') == 'project':      # v0.6: remember what was pulled, for the push guard
        try:
            import guard
            fp = guard.write_base(P, ['images', 'img'] if man.get('no_images') else ())
            print(f'guard: base saved ({len(fp["files"])} source files) — before pushing run guard.py fingerprint on the Mac and pass it to pack --guard')
        except Exception as e: print('guard: base not saved:', e)
    print(('VERIFIED' if not bad else 'NOT VERIFIED') + f": {len(man['files'])} files into {P}" + (f' ({by_dec} media checked by decoded content)' if by_dec else ''))
    sys.exit(1 if bad else 0)


def cmd_check(a):
    P = pathlib.Path(a.project).resolve(); bad, warn = [], []
    for d in LAYOUT:
        if d in ('_to_delete', '.studio'): continue
        if not (P / d).is_dir(): bad.append(f'folder {d}/ missing')
    if (P / 'out').is_dir():
        for f in (P / 'out').iterdir():
            if f.name.startswith('.'): continue
            if a.working: continue        # cloud copy: out/ holds working files that never travel
            if f.is_dir() or not any(fnmatch.fnmatch(f.name, p) for p in FINALS):
                bad.append(f'out/{f.name} is not a final file (out/ = finals only; move it to drafts/)')
    if a.final:
        for p in FINALS:
            if not list((P / 'out').glob(p)): bad.append(f'out/{p} missing')
        for f in ('docs/brief.md', 'docs/script.md', 'docs/fact-sheet.md', 'script.json', 'facts.json', 'state.json'):
            if not (P / f).exists(): bad.append(f'{f} missing')
        if not list((P / 'vo' / 'raw').glob('vo_full.*')): bad.append('vo/raw/vo_full.* (the original take) missing')
        st = P / 'state.json'
        if st.exists() and json.loads(st.read_text()).get('stage') != 'delivered': warn.append('state.json stage is not "delivered"')
    for b in bad: print('FAIL', b)
    for w in warn: print('WARN', w)
    print('LAYOUT OK' if not bad else f'LAYOUT: {len(bad)} problem(s)'); sys.exit(1 if bad else 0)


def cmd_skeleton(a):
    P = pathlib.Path(a.folder).resolve(); P.mkdir(parents=True, exist_ok=True)
    for d in LAYOUT: (P / d).mkdir(parents=True, exist_ok=True)
    me = pathlib.Path(__file__).resolve()
    if me != (P / '.studio' / 'pack.py').resolve(): shutil.copy2(me, P / '.studio' / 'pack.py')
    for extra in ('guard.py', 'state_check.py', 'publint.py', 'series_tracker.py', 'finish.py', 'tidy.py'):
        if (me.parent / extra).exists() and me.parent.resolve() != (P / '.studio').resolve(): shutil.copy2(me.parent / extra, P / '.studio' / extra)
    print(f'skeleton ready in {P}: ' + ', '.join(d + '/' for d in LAYOUT if d != '.studio'))
    print(f'drop the voiceover take in {P / "vo" / "raw"}/ as vo_full.mp3; your photos in {P / "images"}/')


ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
sp = ap.add_subparsers(dest='cmd', required=True)
x = sp.add_parser('pack'); x.add_argument('project'); x.add_argument('--set', choices=['project', 'preview', 'final'], required=True)
x.add_argument('--out', required=True); x.add_argument('--name'); x.add_argument('--mb', type=float, default=14); x.add_argument('--no-images', action='store_true')
x.add_argument('--guard', help='Mac fingerprint json (guard.py fingerprint): refuse to pack if the Mac copy changed since the pull')
x.add_argument('--who'); x.add_argument('--force', action='store_true')
x = sp.add_parser('unpack'); x.add_argument('dir'); x.add_argument('--name', required=True); x.add_argument('--into', required=True)
x.add_argument('--verify-only', action='store_true', help='check files already in place against the manifest')
x = sp.add_parser('check'); x.add_argument('project'); x.add_argument('--final', action='store_true')
x.add_argument('--working', action='store_true', help='cloud working copy: allow working files in out/')
x = sp.add_parser('skeleton'); x.add_argument('folder')
a = ap.parse_args()
{'pack': cmd_pack, 'unpack': cmd_unpack, 'check': cmd_check, 'skeleton': cmd_skeleton}[a.cmd](a)
